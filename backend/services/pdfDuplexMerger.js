const fs = require("fs");
const path = require("path");
const { PDFDocument, PDFName, PDFDict } = require("pdf-lib");

/**
 * Cached buffer and timestamp for back.pdf to prevent repeated disk I/O.
 */
let cachedBackPdf = {
  mtimeMs: 0,
  bytes: null,
  filePath: null,
};

/**
 * Resolves the path to `back.pdf` by searching common locations in backend & frontend.
 * @returns {string|null} Resolved file path, or null if not found.
 */
function resolveBackPdfPath() {
  const candidates = [
    path.resolve(__dirname, "../public/back.pdf"),
    path.resolve(__dirname, "../../frontend/public/back.pdf"),
    path.resolve(process.cwd(), "public/back.pdf"),
    path.resolve(process.cwd(), "backend/public/back.pdf"),
    path.resolve(process.cwd(), "frontend/public/back.pdf"),
    path.resolve(process.cwd(), "../frontend/public/back.pdf"),
  ];

  for (const candidate of candidates) {
    try {
      if (fs.existsSync(candidate)) {
        return candidate;
      }
    } catch {
      // ignore access check error
    }
  }

  return null;
}

/**
 * Loads the raw bytes of `back.pdf`, using an in-memory cache when file is unchanged.
 * @returns {Buffer|null}
 */
function getBackPdfBytes() {
  const filePath = resolveBackPdfPath();
  if (!filePath) {
    return null;
  }

  try {
    const stat = fs.statSync(filePath);
    if (
      cachedBackPdf.bytes &&
      cachedBackPdf.filePath === filePath &&
      cachedBackPdf.mtimeMs === stat.mtimeMs
    ) {
      return cachedBackPdf.bytes;
    }

    const bytes = fs.readFileSync(filePath);
    cachedBackPdf = {
      filePath,
      mtimeMs: stat.mtimeMs,
      bytes,
    };
    return bytes;
  } catch (err) {
    console.warn("[pdfDuplexMerger] Error reading back.pdf:", err.message);
    return null;
  }
}

/**
 * Automatically merges `back.pdf` after every page of the given original PDF buffer.
 *
 * Sequence:
 *   Page 1: Original Page 1 (Front)
 *   Page 2: back.pdf Page 1 (Back)
 *   Page 3: Original Page 2 (Front)
 *   Page 4: back.pdf Page 1 (Back)
 *   ...and so on.
 *
 * Configures the output PDF's `ViewerPreferences` with duplex printing enabled:
 * - Portrait: `DuplexFlipLongEdge`
 * - Landscape: `DuplexFlipShortEdge`
 *
 * If `back.pdf` is missing or invalid, or if an error occurs during merge,
 * the original PDF is safely returned so printing/downloading never fails.
 *
 * @param {Buffer|Uint8Array} originalPdfBuffer - Original PDF Buffer generated by Puppeteer / pdfGenerator
 * @param {Object} [options]
 * @param {boolean} [options.enabled=true] - Set to false to bypass duplex merge
 * @returns {Promise<Buffer>} Combined duplex-ready PDF Buffer
 */
async function attachDuplexBackside(originalPdfBuffer, options = {}) {
  // If explicitly disabled, return original buffer
  if (options.duplex === false || options.includeBackside === false) {
    return Buffer.isBuffer(originalPdfBuffer)
      ? originalPdfBuffer
      : Buffer.from(originalPdfBuffer);
  }

  if (!originalPdfBuffer || originalPdfBuffer.length === 0) {
    return originalPdfBuffer;
  }

  const backBytes = getBackPdfBytes();
  if (!backBytes || backBytes.length === 0) {
    console.warn(
      "[pdfDuplexMerger] 'back.pdf' could not be located in public/ directory. Returning original PDF."
    );
    return Buffer.isBuffer(originalPdfBuffer)
      ? originalPdfBuffer
      : Buffer.from(originalPdfBuffer);
  }

  try {
    const frontDoc = await PDFDocument.load(originalPdfBuffer);
    const frontPageCount = frontDoc.getPageCount();

    if (frontPageCount === 0) {
      return Buffer.isBuffer(originalPdfBuffer)
        ? originalPdfBuffer
        : Buffer.from(originalPdfBuffer);
    }

    const backDoc = await PDFDocument.load(backBytes);
    if (backDoc.getPageCount() === 0) {
      console.warn("[pdfDuplexMerger] 'back.pdf' has 0 pages. Returning original PDF.");
      return Buffer.isBuffer(originalPdfBuffer)
        ? originalPdfBuffer
        : Buffer.from(originalPdfBuffer);
    }

    const mergedDoc = await PDFDocument.create();

    // Embed the first page of back.pdf once as a reusable XObject (minimizes output file size)
    const [embeddedBackPage] = await mergedDoc.embedPdf(backDoc, [0]);

    for (let i = 0; i < frontPageCount; i++) {
      // 1. Front Side: Copy original page
      const [copiedFrontPage] = await mergedDoc.copyPages(frontDoc, [i]);
      mergedDoc.addPage(copiedFrontPage);

      const width = copiedFrontPage.getWidth();
      const height = copiedFrontPage.getHeight();
      const rotation = copiedFrontPage.getRotation();

      // 2. Back Side: Add matching page with identical dimensions and rotation
      const backPage = mergedDoc.addPage([width, height]);
      if (rotation && rotation.angle) {
        backPage.setRotation(rotation);
      }

      backPage.drawPage(embeddedBackPage, {
        x: 0,
        y: 0,
        width,
        height,
      });
    }

    // Configure Duplex printing in PDF ViewerPreferences
    let viewerPreferences = mergedDoc.catalog.get(PDFName.of("ViewerPreferences"));
    if (!viewerPreferences || !(viewerPreferences instanceof PDFDict)) {
      viewerPreferences = mergedDoc.context.obj({});
      mergedDoc.catalog.set(PDFName.of("ViewerPreferences"), viewerPreferences);
    }

    // Standard portrait flipping is Flip on Long Edge; Landscape flipping is Flip on Short Edge
    const firstFrontPage = frontDoc.getPage(0);
    const isPortrait = firstFrontPage.getHeight() >= firstFrontPage.getWidth();
    const duplexMode = isPortrait ? "DuplexFlipLongEdge" : "DuplexFlipShortEdge";

    viewerPreferences.set(PDFName.of("Duplex"), PDFName.of(duplexMode));
    viewerPreferences.set(PDFName.of("PrintScaling"), PDFName.of("None"));

    // If autoPrint requested, embed print JavaScript
    if (options.autoPrint || options.autoprint) {
      mergedDoc.addJavaScript(
        "print",
        "this.print({bUI: true, bSilent: false, bShrinkToFit: true});"
      );
    }

    const mergedBytes = await mergedDoc.save();
    return Buffer.from(mergedBytes);
  } catch (err) {
    console.error("[pdfDuplexMerger] Error applying duplex backside merge:", err);
    // Graceful fallback: return original PDF unchanged
    return Buffer.isBuffer(originalPdfBuffer)
      ? originalPdfBuffer
      : Buffer.from(originalPdfBuffer);
  }
}

module.exports = {
  attachDuplexBackside,
  resolveBackPdfPath,
  getBackPdfBytes,
};

